package com.fem.linexa.data.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import com.fem.linexa.domain.security.SecretCipher
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.inject.Inject
import javax.inject.Singleton

/**
 * [SecretCipher] backed by an AES-256-GCM key that lives in the Android Keystore.
 *
 * The key never leaves the Keystore (the app only ever holds a handle), is created on
 * first use, and requires no user authentication — the runtime must be able to start a
 * desktop without a prompt. It is excluded from backup and device transfer by the
 * platform, which matches the Room database (already excluded in `backup_rules.xml`
 * and `data_extraction_rules.xml`): ciphertext and key are lost together, never apart.
 *
 * Blob layout: `IV (12 bytes) || ciphertext || GCM tag`. The IV is generated by the
 * Keystore for every encryption (randomized encryption is required by the spec), never
 * supplied by us. Every failure throws; the caller (`SecretAttributeCodec`) maps that to
 * a typed result, so nothing here ever falls back to returning plaintext.
 */
@Singleton
class AndroidKeystoreSecretCipher @Inject constructor() : SecretCipher {

    @Volatile
    private var cachedKey: SecretKey? = null

    override fun encrypt(plaintext: ByteArray, aad: ByteArray): ByteArray = guarded {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        cipher.updateAAD(aad)
        val iv = cipher.iv
        check(iv != null && iv.size == IV_BYTES) { "Keystore returned an unexpected IV" }
        iv + cipher.doFinal(plaintext)
    }

    override fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray = guarded {
        require(blob.size > IV_BYTES) { "Ciphertext blob is too short" }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(
            Cipher.DECRYPT_MODE,
            key(),
            GCMParameterSpec(TAG_BITS, blob, 0, IV_BYTES)
        )
        cipher.updateAAD(aad)
        cipher.doFinal(blob, IV_BYTES, blob.size - IV_BYTES)
    }

    /** Drops the cached key handle on failure so the next call re-resolves it. */
    private inline fun <T> guarded(block: () -> T): T = try {
        block()
    } catch (e: Exception) {
        cachedKey = null
        throw e
    }

    private fun key(): SecretKey {
        cachedKey?.let { return it }
        synchronized(this) {
            cachedKey?.let { return it }
            val keyStore = KeyStore.getInstance(PROVIDER).apply { load(null) }
            val existing = keyStore.getKey(ALIAS, null) as? SecretKey
            val key = existing ?: generate()
            cachedKey = key
            return key
        }
    }

    private fun generate(): SecretKey {
        val spec = KeyGenParameterSpec.Builder(
            ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(KEY_BITS)
            .build()
        return KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
            .apply { init(spec) }
            .generateKey()
    }

    private companion object {
        const val PROVIDER = "AndroidKeyStore"
        const val ALIAS = "linexa.workspace.secrets.v1"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val KEY_BITS = 256
        const val IV_BYTES = 12
        const val TAG_BITS = 128
    }
}
